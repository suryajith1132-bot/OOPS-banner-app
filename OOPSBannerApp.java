public class OOPSBannerApp {

    public static void printO() {
        System.out.println("*****");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*****");
    }

    public static void printP() {
        System.out.println("*****");
        System.out.println("*   *");
        System.out.println("*****");
        System.out.println("*");
        System.out.println("*");
    }

    public static void printS() {
        System.out.println("*****");
        System.out.println("*");
        System.out.println("*****");
        System.out.println("    *");
        System.out.println("*****");
    }

    public static void main(String[] args) {

        printO();
        System.out.println();

        printO();
        System.out.println();

        printP();
        System.out.println();

        printS();
    }
}
